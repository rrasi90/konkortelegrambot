// ادغام خودکار دایرةالمعارف مکمل ۱۰۰ صفحه‌ای هر درس در بانک کتب مرجع
for (const supp of COURSE_ENCYCLOPEDIA_SUPPLEMENTS) {
  const targetBook = REFERENCE_BOOKS_DATABASE.find((b) => b.id === supp.bookId);
  if (targetBook) {
    for (const ch of supp.extraChapters) {
      if (!targetBook.highYieldChapters.some((c) => c.chapterTitle === ch.chapterTitle)) {
        targetBook.highYieldChapters.push(ch);
      }
    }
    for (const note of supp.extraGoldenNotes) {
      if (!targetBook.goldenNotesCheatSheet.includes(note)) {
        targetBook.goldenNotesCheatSheet.push(note);
      }
    }
    for (const q of supp.extraQuestions) {
      if (!targetBook.sampleKonkorQuestions.some((sq) => sq.id === q.id)) {
        targetBook.sampleKonkorQuestions.push(q);
      }
    }
  }
}

/**
 * تولیدکننده خودکار فایل جزوه خلاصه فصول، فرمول‌نامه و بانک تست تشریحی (.md)
 * برای دانلود مستقیم توسط داوطلب جهت مطالعه آفلاین و پرینت
 */
export function generateBookHandoutMarkdown(book: ReferenceBookItem): string {
  const lines: string[] = [];
  lines.push(`# جزوه جامع، خلاصه فصول و بانک تست تشریحی: ${book.courseName}`);
  lines.push(`**کتاب مرجع:** ${book.bookTitle}`);
  lines.push(`**مؤلفان:** ${book.authors}`);
  lines.push(`**انتشارات / گردآورندگان:** ${book.translatorsOrCompilers}`);
  lines.push(`**ضریب در کنکور ارشد:** ${book.coefficientMaster}`);
  lines.push(`**ضریب در کنکور دکتری:** ${book.coefficientPhd}`);
  lines.push(`\n---\n`);
  lines.push(`## چرا این منبع در کنکور حیاتی است؟`);
  lines.push(book.whyImportant);
  lines.push(`\n---\n`);
  lines.push(`## بخش اول: خلاصه فصل‌به‌فصل و نکات کلیدی`);

  book.highYieldChapters.forEach((ch, idx) => {
    lines.push(`\n### ${idx + 1}. [${ch.chapterNumber}] ${ch.chapterTitle} (${ch.examImportance})`);
    ch.keyPointsSummary.forEach((pt) => {
      lines.push(`- ${pt}`);
    });
    if (ch.formulasOrModels && ch.formulasOrModels.length > 0) {
      lines.push(`\n**فرمول‌ها و مدل‌های مرجع این فصل:**`);
      ch.formulasOrModels.forEach((fm) => {
        lines.push(`> ${fm}`);
      });
    }
  });

  lines.push(`\n---\n`);
  lines.push(`## بخش دوم: تقلب‌نامه و نکات طلایی شب آزمون`);
  book.goldenNotesCheatSheet.forEach((tip, idx) => {
    lines.push(`${idx + 1}. ${tip}`);
  });

  lines.push(`\n---\n`);
  lines.push(`## بخش سوم: بانک تست چهارگزینه‌ای با پاسخ کاملاً تشریحی و تحلیل دام طراح`);
  book.sampleKonkorQuestions.forEach((q, idx) => {
    lines.push(`\n### سؤال ${idx + 1} (${q.examTitle} — سال ${q.examYear} | مقطع ${q.degreeLevel} | مبحث: ${q.chapterTopic})`);
    lines.push(`**صورت سؤال:** ${q.questionText}\n`);
    q.options.forEach((opt, oIdx) => {
      lines.push(`${oIdx + 1}) ${opt}`);
    });
    lines.push(`\n- **پاسخ صحیح:** گزینه ${q.correctOption + 1}`);
    lines.push(`- **پاسخ تشریحی کامل:** ${q.detailedAnswer}`);
    lines.push(`- **دام طراح کنکور:** ${q.konkorTrap}`);
  });

  return lines.join('\n');
}

export function generateAllBooksMasterHandoutMarkdown(): string {
  const header = `# پکیج کامل جزوات خلاصه فصول، فرمول‌نامه و بانک تست تشریحی کنکور کارشناسی ارشد و دکتری مدیریت\nشامل هر ۷ درس طلایی کارشناسی ارشد مدیریت بازرگانی + منابع تخصصی مدیریت صنعتی و مدیریت فناوری\n\n====================\n\n`;
  return (
    header +
    REFERENCE_BOOKS_DATABASE.map((b) => generateBookHandoutMarkdown(b)).join(
      '\n\n============================================================\n\n'
    )
  );
}
