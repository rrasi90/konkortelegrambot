/**
 * یافتن درس‌نامه کامل برای یک شناسهٔ گره (nodeId)
 */
export function findLessonForNode(nodeId: string): LessonTopic | null {
  for (const course of COURSES_LESSONS) {
    for (const topic of course.topics) {
      if (topic.id === nodeId) return topic;
    }
  }
  // تطبیق پیشوندی یا فازی (مثلاً sm.portfolio تطبیق با sm.*)
  const prefix = nodeId.split('.')[0];
  for (const course of COURSES_LESSONS) {
    for (const topic of course.topics) {
      if (topic.id.startsWith(prefix + '.')) return topic;
    }
  }
  return null;
}
